// Product 100.., indoor 200.., outdoor 300.. — grouped, and clear of the legacy 0–28 range.
const rows = [
  ...PRODUCT_STYLES.map((s, i) => ({ s, tab: 'PRODUCT', order: 100 + i })),
  ...MODEL_STYLES.filter((s) => s.id.startsWith('MI-')).map((s, i) => ({
    s,
    tab: 'MODEL',
    order: 200 + i,
  })),
  ...MODEL_STYLES.filter((s) => s.id.startsWith('MO-')).map((s, i) => ({
    s,
    tab: 'MODEL',
    order: 300 + i,
  })),
];

const TAG = '$kp$';
const q = (v) => {
  if (v.includes(TAG)) throw new Error(`text contains ${TAG}: ${v.slice(0, 40)}`);
  return `${TAG}${v}${TAG}`;
};

const values = rows.map(({ s, tab, order }) => {
  const desc = DESCRIPTION[s.id];
  if (!desc) throw new Error(`no description for ${s.id}`);
  const slug = s.id.toLowerCase();
  return `  (gen_random_uuid()::text, '${slug}', ${q(s.label)}, ${q(desc)}, ${q(s.prompt)}, '${tab}', 'DRAFT', ARRAY['STARTER','GROWTH','PRO']::"SubscriptionPlan"[], NULL, ARRAY[]::TEXT[], ${order}, now())`;
});

const sql = `-- F-032 option matrix: seed the owner's ${rows.length} Product Only / Model Only styles
-- (docs/tasks/pending/studio-shoot-option-matrix.md §14, rollout task 2.3).
--
-- ADDITIVE AND INVISIBLE. Every row is inserted as DRAFT, so GET /products/studio-styles
-- and POST /studio-shoot (both require status = 'PUBLISHED') do not see them until the
-- owner publishes each row in Admin -> Studio Styles after a real-photo bench. Nothing
-- existing is changed or retired here: retiring the legacy catalog while the new rows are
-- still DRAFT would leave retailers with an empty picker. Hide the legacy rows from the
-- admin UI (or a follow-up migration) once the new ones are published (rollout 2.4/2.7).
--
-- * slug = lower-cased style id ('ps-03', 'mi-02', 'mo-05'). poolsForSlug() in
--   @kanchuki/shared and the mobile Indoor/Outdoor grouping key off this convention.
-- * prompt keeps the {{Pool}} tokens; the studio-shoot job resolves one pick per
--   generation from the shared pools (the DB has no column for pools).
-- * engine NULL = default cascade; per-style routing waits on bench run 2 (rollout 2.5).
-- * plans = all three: AI Studio is gated by the STUDIO_SHOOT quota, not by plan.
-- * ON CONFLICT DO NOTHING: re-running never overwrites an admin's edits.
-- * Generated by scripts/gen-studio-option-matrix-seed.mjs from packages/shared.
--
-- Rollback: DELETE FROM studio_styles WHERE slug ~ '^(ps|mi|mo)-[0-9]{2}$' AND status = 'DRAFT';
-- (never delete a PUBLISHED row that has usage_count > 0 — hide it instead).

INSERT INTO studio_styles (id, slug, label, description, prompt, tab, status, plans, engine, audience, sort_order, updated_at) VALUES
${values.join(',\n')}
ON CONFLICT (slug) DO NOTHING;
`;

const dir = new URL(
  '../packages/db/prisma/migrations/123_studio_styles_option_matrix/',
  import.meta.url,
);
mkdirSync(dir, { recursive: true });
writeFileSync(new URL('migration.sql', dir), sql, 'utf8');
console.log(`wrote ${rows.length} rows`);
